// Generates src/shared/lib/countries.data.ts (SF-39): the officially assigned
// ISO 3166-1 alpha-2 codes the API accepts (`country_code`), with their names
// in every app locale, from Node's full ICU (Unicode CLDR). Hermes has no
// `Intl.DisplayNames`, so the app ships this table instead of deriving it at
// runtime as the web client does; the rule is the web client's
// (simplefit-platform src/shared/lib/countries.ts): every two-letter code CLDR
// names, minus every code ISO 3166-1 does not officially assign.
//
// Run with `pnpm countries:generate`; countries.test.ts re-derives the table
// and fails when it is stale.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

import countriesSource from "./countries-source.js";

const { assignedCountryCodes, localizedCountryNames } = countriesSource;

const codes = assignedCountryCodes();
const names = localizedCountryNames(codes);
const body = `// Generated by scripts/generate-countries.mjs from Unicode CLDR. Do not edit.
export const COUNTRY_CODES = ${JSON.stringify(codes)} as const;

export const COUNTRY_NAMES: Record<string, Record<string, string>> = ${JSON.stringify(names, null, 2)};
`;
const target = fileURLToPath(new URL("../src/shared/lib/countries.data.ts", import.meta.url));
// Formatted with the repository's Prettier config, as the route generator does.
const formatted = await prettier.format(body, {
  ...(await prettier.resolveConfig(target)),
  filepath: target,
});
writeFileSync(target, formatted);
console.log(`countries: ${codes.length} codes in ${Object.keys(names).length} locales`);
