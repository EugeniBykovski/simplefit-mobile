// Generates src/shared/lib/time-zones.data.ts (SF-65): the IANA region zones
// (and UTC) a coach can plan a training session in, from Node's full ICU.
// Hermes has no `Intl.supportedValuesOf`, so the app ships this list instead
// of reading it at runtime as the web client does (simplefit-platform
// src/shared/lib/time-zone.ts, the same rule: region zones and UTC, never an
// `Etc/` zone). The app still checks each zone against the device's own zone
// data before offering it; the backend validates the one it receives.
//
// Run with `pnpm time-zones:generate`.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

const zones = [
  "UTC",
  ...Intl.supportedValuesOf("timeZone").filter(
    (zone) => /^[A-Za-z_]+(\/[A-Za-z0-9_+-]+)+$/.test(zone) && !zone.startsWith("Etc/"),
  ),
];
const body = `// Generated by scripts/generate-time-zones.mjs from Node's ICU (tz ${process.versions.tz}). Do not edit.
export const TIME_ZONES: readonly string[] = ${JSON.stringify(zones)};
`;
const target = fileURLToPath(new URL("../src/shared/lib/time-zones.data.ts", import.meta.url));
const formatted = await prettier.format(body, {
  ...(await prettier.resolveConfig(target)),
  filepath: target,
});
writeFileSync(target, formatted);
console.log(`time zones: ${zones.length}`);
